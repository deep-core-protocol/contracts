/* ============================================================================
   Emits one deploy config per target chain, into this directory.

   Run: node packages/core/script/config/_generate.mjs

   The chain list and every `supportsEip1153` flag come from
   apps/web/src/data/chains.generated.ts, which is itself generated by
   apps/web/scripts/sync-chains.mjs after probing each network with a live
   TSTORE call. Nothing here is hand-asserted about a chain's EVM version.

   WHY OWNERS ARE LEFT EMPTY ON MAINNET. `01_DeployVault.s.sol` ends with
   `transferOwnership(getAddressFromConfig("poolOwner"))`, so whatever this file
   says becomes the owner of the Vault the moment it is deployed — and
   `Vault.registerApp` is irreversible. Writing a plausible EOA here to "fill it
   in for now" is precisely how a mainnet Vault ends up owned by one key. So
   every mainnet config ships with "0x", which makes the deploy FAIL rather than
   succeed with the wrong owner. Fill it with that chain's DeepCoreTimelock, which
   must therefore be deployed first.

   Testnets may use a deployer EOA (there is nothing to lose, and pools need to
   be iterated on), but this generator never writes one: it ships "0x" and the
   operator fills in that run's deployer.

   ONLY TARGET CHAINS. DeepCore launches on HyperEVM (999) only. The chain list
   in chains.generated.ts is wider (the site supports many chains), but a config
   here is a deployment intent, so only the keys in TARGETS are emitted. Add a
   key to TARGETS when the owner decides to deploy on that chain; never emit a
   config for a chain nobody is deploying to.
   ========================================================================== */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const src = readFileSync(
  join(here, '../../../../apps/web/src/data/chains.generated.ts'),
  'utf8',
)

const re =
  /key:\s*'([^']+)'[\s\S]*?chainId:\s*(\d+)[\s\S]*?name:\s*'([^']+)'[\s\S]*?network:\s*'([^']+)'[\s\S]*?supportsEip1153:\s*(true|false)/g

/** Chains DeepCore deploys to. Owner decision: HyperEVM mainnet only. */
const TARGETS = new Set(['hyperevm'])

let m
let count = 0
while ((m = re.exec(src))) {
  const [, key, id, name, network, e1153] = m
  const mainnet = network === 'mainnet'
  const cancun = e1153 === 'true'

  if (!TARGETS.has(key)) continue

  const cfg = {
    _comment: `DeepCore Protocol — ${name} (${id}). ${mainnet ? 'MAINNET' : 'Testnet'} topology.`,
    _profile: cancun
      ? 'default — chain supports EIP-1153, probed live. Build with `forge build`.'
      : 'legacy — chain has NO EIP-1153. Build with `FOUNDRY_PROFILE=legacy`. BackendGuard asserts this at deploy.',
    _chainId: Number(id),
    _supportsEip1153: cancun,

    _create3Note:
      'Deploy our OWN factory first (00_DeployCreate3Factory). PancakeSwap\'s is onlyWhitelisted and owned by an address we do not control.',
    create3Factory: '0x',

    _ownerNote: mainnet
      ? 'MAINNET — never an EOA. One timelock tier (Custody 48h, packages/governance/script/DeployGovernanceMainnet.s.sol, the Safe as sole proposer, address(0) as executor, a dedicated canceller); there is no Policy tier. protocolFeeControllerOwner = the DeepCore governance Safe (not created yet). poolOwner = what the Vault and both pool-manager owner wrappers are NOMINATED to (Ownable2Step): the Safe, which then queues the handover to the custody timelock. The Safe must exist on this chain (code present) first. Left as "0x" on purpose so a deploy fails loudly rather than succeeding with the wrong owner.'
      : 'TESTNET — a deployer EOA is fine; pools need to be iterated on. Fill in the deployer for this run.',
    poolOwner: '0x',
    protocolFeeControllerOwner: '0x',

    vault: '0x',
    clPoolManager: '0x',
    binPoolManager: '0x',
    clProtocolFeeController: '0x',
    binProtocolFeeController: '0x',
    clPoolManagerOwnerContract: '0x',
    binPoolManagerOwnerContract: '0x',
  }

  writeFileSync(join(here, `deepcore-${key}.json`), JSON.stringify(cfg, null, 4) + '\n')
  count++
}
console.log(`wrote ${count} config(s) for ${[...TARGETS].join(', ')}`)
